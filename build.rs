use image::codecs::ico::{IcoEncoder, IcoFrame};
use std::collections::BTreeSet;
use std::path::Path;
use std::{env, fs, path::PathBuf};

const TEMPLATE_ROOT: &str = "assets/AFKJourney";

fn main() {
    println!("cargo:rerun-if-changed=assets/adbhelper-logo-v2.png");
    println!("cargo:rerun-if-changed=build.rs");
    generate_template_table();
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("Cargo OUT_DIR"));
    let logo = image::open("assets/adbhelper-logo-v2.png").expect("decode application logo");
    let mut frames = Vec::new();
    for size in [16, 24, 32, 48, 64, 128, 256] {
        let scaled = logo
            .resize(size, size, image::imageops::FilterType::Lanczos3)
            .to_rgba8();
        let mut canvas = image::RgbaImage::new(size, size);
        image::imageops::overlay(
            &mut canvas,
            &scaled,
            i64::from((size - scaled.width()) / 2),
            i64::from((size - scaled.height()) / 2),
        );
        frames.push(
            IcoFrame::as_png(canvas.as_raw(), size, size, image::ExtendedColorType::Rgba8)
                .expect("encode icon size"),
        );
    }
    let icon = out.join("adbhelper.ico");
    IcoEncoder::new(fs::File::create(&icon).expect("create icon"))
        .encode_images(&frames)
        .expect("encode application icon");
    let resource = out.join("adbhelper.rc");
    fs::write(
        &resource,
        format!(
            "1 ICON \"{}\"\n",
            icon.display().to_string().replace('\\', "/")
        ),
    )
    .expect("write icon resource");
    embed_resource::compile_for(&resource, ["adbhelper"], embed_resource::NONE)
        .manifest_required()
        .expect("embed Windows application icon");
}

/// Embeds every template the source code asks for, and nothing else.
///
/// Template names are the string literals ending in `.png` in `src/`, relative
/// to `assets/AFKJourney`. Names built at runtime (`format!("equipment/{class}.png")`)
/// embed every file that fits the pattern in that folder. A literal that names a
/// template folder but has no file stops the build, so a typo never reaches users.
fn generate_template_table() {
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed={TEMPLATE_ROOT}");
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("Cargo manifest dir"));
    let root = manifest.join(TEMPLATE_ROOT);
    let mut available = BTreeSet::new();
    collect_files(&root, &root, &mut available);
    let folders: BTreeSet<String> = available
        .iter()
        .filter_map(|path| path.split_once('/').map(|(folder, _)| folder.to_owned()))
        .collect();

    let mut sources = Vec::new();
    collect_sources(&manifest.join("src"), &mut sources);
    let mut used = BTreeSet::new();
    let mut missing = BTreeSet::new();
    for source in &sources {
        let code = fs::read_to_string(source).expect("read source file");
        for literal in png_literals(&code) {
            if literal.contains('{') {
                let parts = pattern_parts(&literal);
                used.extend(available.iter().filter(|path| fits(path, &parts)).cloned());
            } else if available.contains(&literal) {
                used.insert(literal);
            } else if literal
                .split_once('/')
                .is_some_and(|(folder, _)| folders.contains(folder))
            {
                missing.insert(literal);
            }
        }
    }
    if !missing.is_empty() {
        panic!(
            "Templates are referenced in src/ but missing in {TEMPLATE_ROOT}: {}",
            missing.into_iter().collect::<Vec<_>>().join(", ")
        );
    }

    let mut table = String::from(
        "// Generated by build.rs from the template names in src/. Do not edit.\n\
         pub(super) fn embedded(relative_path: &str) -> Option<&'static [u8]> {\n    \
         Some(match relative_path {\n",
    );
    for path in &used {
        let file = root.join(path).display().to_string().replace('\\', "/");
        table.push_str(&format!(
            "        {path:?} => include_bytes!({file:?}).as_slice(),\n"
        ));
    }
    table.push_str("        _ => return None,\n    })\n}\n\n");
    table.push_str(&format!(
        "#[cfg(test)]\npub(super) const EMBEDDED: &[&str] = &{:?};\n",
        used.iter().collect::<Vec<_>>()
    ));
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("Cargo OUT_DIR"));
    fs::write(out.join("templates.rs"), table).expect("write template table");
}

fn collect_files(root: &Path, directory: &Path, files: &mut BTreeSet<String>) {
    let mut entries: Vec<_> = fs::read_dir(directory)
        .expect("read template folder")
        .map(|entry| entry.expect("read template entry").path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            collect_files(root, &path, files);
        } else if path.extension().is_some_and(|extension| extension == "png") {
            let relative = path.strip_prefix(root).expect("template below root");
            files.insert(relative.to_string_lossy().replace('\\', "/"));
        }
    }
}

fn collect_sources(directory: &Path, sources: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(directory).expect("read source folder") {
        let path = entry.expect("read source entry").path();
        if path.is_dir() {
            collect_sources(&path, sources);
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            sources.push(path);
        }
    }
    sources.sort();
}

/// Plain string literals in Rust source that end in `.png` (escapes kept verbatim).
fn png_literals(code: &str) -> Vec<String> {
    let mut literals = Vec::new();
    let mut chars = code.char_indices().peekable();
    while let Some((index, character)) = chars.next() {
        match character {
            '/' if code[index..].starts_with("//") => {
                while chars.peek().is_some_and(|&(_, next)| next != '\n') {
                    chars.next();
                }
            }
            '\'' => {
                // Skip char literals such as '"' so they do not open a string.
                let rest = &code[index + 1..];
                let length = if rest.starts_with('\\') { 2 } else { 1 };
                if rest.chars().nth(length) == Some('\'') {
                    for _ in 0..=length {
                        chars.next();
                    }
                }
            }
            '"' => {
                let mut literal = String::new();
                while let Some((_, next)) = chars.next() {
                    match next {
                        '\\' => {
                            if let Some((_, escaped)) = chars.next() {
                                literal.push('\\');
                                literal.push(escaped);
                            }
                        }
                        '"' => break,
                        other => literal.push(other),
                    }
                }
                if literal.ends_with(".png") && !literal.contains('\\') {
                    literals.push(literal);
                }
            }
            _ => {}
        }
    }
    literals
}

/// Splits `legend_trials/banner_{}.png` into the fixed parts around placeholders.
fn pattern_parts(pattern: &str) -> Vec<String> {
    let mut parts = vec![String::new()];
    let mut inside = false;
    for character in pattern.chars() {
        match character {
            '{' => inside = true,
            '}' if inside => {
                inside = false;
                parts.push(String::new());
            }
            _ if !inside => parts.last_mut().expect("pattern part").push(character),
            _ => {}
        }
    }
    parts
}

/// A placeholder stands for one or more characters within a single folder level.
fn fits(path: &str, parts: &[String]) -> bool {
    let (first, rest) = parts.split_first().expect("pattern has a first part");
    let Some(mut remaining) = path.strip_prefix(first.as_str()) else {
        return false;
    };
    for (index, part) in rest.iter().enumerate() {
        let last = index + 1 == rest.len();
        let position = if last {
            remaining
                .len()
                .checked_sub(part.len())
                .filter(|&at| remaining[at..] == **part)
        } else {
            remaining
                .get(1..)
                .and_then(|tail| tail.find(part.as_str()))
                .map(|at| at + 1)
        };
        let Some(position) = position else {
            return false;
        };
        let filled = &remaining[..position];
        if filled.is_empty() || filled.contains('/') {
            return false;
        }
        remaining = &remaining[position + part.len()..];
    }
    remaining.is_empty()
}
